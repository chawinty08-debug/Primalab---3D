let FAILS = 0;
/* Inverse-kinematics validation (run: node tests/ik_validation.js)
   1) radian rotation helpers vs the degree versions, Euler decomposition round trip
   2) recovery of known joint angles from markers generated by the IK model itself (0 and 0.5 mm noise, 40-frame RTHI gap)
   3) the bundled synthetic CMJ: IK vs segment optimisation (6DOF) */
const E = require('../engine.js');
const D2R = Math.PI / 180;
// 1) radian rotation helpers vs existing degree versions + Euler inverses
let e1 = 0, e2 = 0;
for (let i = 0; i < 200; i++) {
  const a = (Math.random() - .5) * 300, b = (Math.random() - .5) * 160, g = (Math.random() - .5) * 300;
  const A = E.rotZXYr(a * D2R, b * D2R, g * D2R), B = E.rotZXY(a, b, g), C = E.rotYXZr(a * D2R, b * D2R, g * D2R), Dm = E.rotYXZ(a, b, g);
  for (let k = 0; k < 9; k++) { e1 = Math.max(e1, Math.abs(A[k] - B[k]), Math.abs(C[k] - Dm[k])); }
  const z = E.cardanZXY(B), y = E.cardanYXZ(Dm), w = x => ((x + 540) % 360) - 180;
  e2 = Math.max(e2, Math.abs(w(z[0] - a)), Math.abs(z[1] - b), Math.abs(w(z[2] - g)), Math.abs(w(y[0] - a)), Math.abs(y[1] - b), Math.abs(w(y[2] - g)));
}
console.log('rot helpers max err', e1.toExponential(1), '· Euler inverse max err (deg)', e2.toExponential(1));

// 18-marker variant of the synthetic sample (same as regress.js)
function to18() {
  const d = E.makeSyntheticCMJ(), nF = d.nFrames, nM0 = d.nM;
  const names = d.base.slice(0, 16).filter(n => !/TIB/.test(n)).concat(['LKNEM', 'RKNEM', 'LANKM', 'RANKM']);
  const nM = names.length, pts = new Float32Array(nF * nM * 3), vis = new Uint8Array(nF * nM);
  for (let f = 0; f < nF; f++) names.forEach((n, i) => {
    let src = n, dy = 0; if (/KNEM|ANKM/.test(n)) { src = n.slice(0, 4); dy = (n[0] === 'L' ? -1 : 1) * (n.includes('KNE') ? 0.10 : 0.07); }
    const k = f * nM0 + d.base.indexOf(src); vis[f * nM + i] = d.vis[k];
    for (let a = 0; a < 3; a++) pts[(f * nM + i) * 3 + a] = d.pts[k * 3 + a] + (a === 1 ? dy : 0);
  });
  return E.finishDataset({ name: 's18', rate: d.rate, nFrames: nF, firstFrame: 1, labels: names, pts, vis, plates: d.plates, events: [], warnings: [], info: {} });
}
// 2) recovery: markers generated by the IK model itself from random smooth joint trajectories
function recovery(label, ds0, kopt, modelId, noise) {
  const kin = E.computeLowerBody(ds0, kopt), M = E.buildIKModel(kin, modelId);
  const nF = 300, rate = 200, names = M.marks.map(m => m.name), nM = names.length;
  const pts = new Float32Array(nF * nM * 3), vis = new Uint8Array(nF * nM).fill(1), truth = [];
  const rnd = (() => { let s = 12345; return () => (s = (s * 16807) % 2147483647) / 2147483647; })();
  const gauss = () => Math.sqrt(-2 * Math.log(rnd() + 1e-12)) * Math.cos(2 * Math.PI * rnd());
  const amp = M.joints.map(j => j.free.map(fr => (fr ? [30, 12, 15].map(v => v * D2R) : [0, 0, 0])));
  const ph = M.joints.map(() => [rnd() * 6, rnd() * 6, rnd() * 6]);
  for (let f = 0; f < nF; f++) {
    const t = f / rate;
    const q = M.joints.map((j, i) => j.q0.map((v, c) => v + (j.free[c] ? amp[i][c][c] * Math.sin(2 * Math.PI * 1.1 * t + ph[i][c]) : 0)));
    const Rp = E.rotZXYr(0.4 * Math.sin(t * 3), 0.15 * Math.sin(t * 5), 0.2 * Math.sin(t * 2));
    const P = E.ikForward(M, Rp, [0.3 * t, 0.05 * Math.sin(t), 0.9 + 0.1 * Math.sin(4 * t)], q);
    truth.push(P);
    M.marks.forEach((m, i) => { const S = P[m.seg]; for (let a = 0; a < 3; a++) pts[(f * nM + i) * 3 + a] = S.o[a] + S.R[a * 3] * m.p[0] + S.R[a * 3 + 1] * m.p[1] + S.R[a * 3 + 2] * m.p[2] + noise * gauss(); });
  }
  // a gap: right THI missing for 40 frames
  const iT = names.indexOf('RTHI'); for (let f = 100; f < 140; f++) vis[f * nM + iT] = 0;
  const ds = E.finishDataset({ name: 'gen', rate, nFrames: nF, firstFrame: 1, labels: names, pts, vis, plates: [], events: [], warnings: [], info: {} });
  const t0 = Date.now(), ik = E.computeIK(ds, kin, { model: modelId }), ms = Date.now() - t0;
  let err = 0, n = 0, mx = 0;
  for (let f = 0; f < nF; f++) for (const [jn, sg, rf] of E.LB_JOINTS) {
    const tr = E.jointEuler(jn, truth[f][rf].R, truth[f][sg].R, M.PIG, kin.pigOffset);
    ['a', 'b', 'g'].forEach((c, k) => { const v = ik.angles[jn][c][f]; if (v === v) { let d = Math.abs(((v - tr[k]) % 360 + 540) % 360 - 180); err += d * d; n++; if (d > mx) mx = d; } });
  }
  if (!(Math.sqrt(err / n) < (noise ? 1.0 : 0.1))) { FAILS++; console.log('  FAIL: angle RMSE ' + Math.sqrt(err / n).toFixed(3) + '°'); }
  console.log(label.padEnd(26), 'model', modelId, '· DOF', M.nPar, '· angle RMSE', Math.sqrt(err / n).toFixed(3) + '°', 'max', mx.toFixed(2) + '°', '· marker RMS', (ik.residual.mean * 1000).toFixed(2), 'mm', '·', ms, 'ms', '· it/frame', ik.iterMean.toFixed(1));
}
const s16 = E.makeSyntheticCMJ(), s18 = to18();
for (const noise of [0, 0.0005]) {
  console.log('--- noise', noise * 1000, 'mm');
  recovery('conv16 Cardan Z-X-Y', s16, {}, 'sph', noise);
  recovery('conv16 Cardan Z-X-Y', s16, {}, 'lu', noise);
  recovery('bad18 PiG Y-X-Z', s18, { convention: 'pig' }, 'sph', noise);
  recovery('bad18 PiG Y-X-Z', s18, { convention: 'pig' }, 'lu', noise);
}
// 3) the synthetic CMJ itself: IK vs 6DOF
for (const [lbl, ds, o] of [['CMJ conv16', s16, {}], ['CMJ bad18 PiG', s18, { convention: 'pig' }]]) {
  const kin = E.computeLowerBody(ds, o);
  for (const m of ['sph', 'lu']) {
    const ik = E.computeIK(ds, kin, { model: m });
    let d = 0; for (const j of ['RHip', 'RKnee', 'RAnkle']) for (let f = 0; f < ds.nFrames; f++) { const x = ik.angles[j].a[f] - kin.angles[j].a[f]; if (x === x) d = Math.max(d, Math.abs(x)); }
    console.log(lbl, m, '· residual mean', (ik.residual.mean * 1000).toFixed(2), 'mm max', (ik.residual.max * 1000).toFixed(2), 'mm · max |IK − 6DOF| sagittal', d.toFixed(2) + '°', '· warnings:', ik.warnings.length ? ik.warnings.join(' | ') : 'none');
  }
}
console.log(FAILS ? 'IK VALIDATION FAIL (' + FAILS + ')' : 'IK VALIDATION PASS'); process.exit(FAILS ? 1 : 0);
